"""How much of the rate contrast can the windowed guide represent at all?

The guide gives each window of W bins one softmax over "no onset here" or "onset at
position k", so two onsets in one window are one onset to it. That caps the recoverable
rate, and caps it harder where the rate is higher -- after the injection -- which
attenuates the contrast before any optimisation happens. Measured on onsets drawn from
the same process the cohorts are drawn from, so this is counting, not fitting.
"""
import argparse
import math
import pathlib

import numpy as np
import torch
import yaml

from photosvi.experiments.cohort import spec_from_config
from photosvi.models.points import PhasicEventProcess, build_kernel

ap = argparse.ArgumentParser()
ap.add_argument("--config", default="configs/cohort_power_48.yaml")
ap.add_argument("--seeds", type=int, default=8)
ap.add_argument("--macros", default=None)
a = ap.parse_args()

cfg = yaml.safe_load(open(a.config))
spec = spec_from_config(cfg, 0.4)
W, dt = cfg["fit"]["window"], spec.dt
kern = build_kernel(dict(spec.kernel), spec.kernel_length, dt)
T, inj = spec.T, spec.inj_t


def draw(beta_inj, seed):
    g = torch.Generator().manual_seed(seed)
    ex = PhasicEventProcess(kern, beta0=spec.beta0_mean, beta_inj=beta_inj,
                            mu_a=spec.mu_a, sigma_a=spec.sigma_a, dt=dt,
                            history=None).sample(T, inj, 1, g)
    on = ex["s"][0].nonzero().reshape(-1).numpy()
    pre, post = on[on < inj], on[on >= inj]
    # "kept" is how many the guide could place: one per occupied window.
    return (len(np.unique(pre // W)), len(pre),
            len(np.unique(post // W)), len(post))


print(f"window {W} bins ({W * dt * 1000:.0f} ms), simulated contrast "
      f"{spec.mu_drug[1] - spec.mu_drug[0]:.2f}\n")
print(f"{'seed':>4}{'true':>10}{'representable':>15}{'events/min post':>17}")
ts, gs, RATES = [], [], []
for seed in range(a.seeds):
    kpv, npv, kqv, nqv = draw(spec.mu_drug[0], seed)          # vehicle
    kpt, npt, kqt, nqt = draw(spec.mu_drug[1], seed + 1000)   # treated
    rate = lambda n, bins: n / (bins * dt) * 60                      # noqa: E731
    t = (math.log(rate(nqt, T - inj) / rate(npt, inj))
         - math.log(rate(nqv, T - inj) / rate(npv, inj)))
    g = (math.log(rate(kqt, T - inj) / rate(kpt, inj))
         - math.log(rate(kqv, T - inj) / rate(kpv, inj)))
    ts.append(t)
    gs.append(g)
    RATES.append(rate(nqt, T - inj))
    print(f"{seed:>4}{t:>10.3f}{g:>15.3f}{rate(nqt, T - inj):>17.0f}")
mt, mg = float(np.mean(ts)), float(np.mean(gs))
print(f"\nmean true {mt:+.3f}, mean representable {mg:+.3f}")
print(f"the one-onset-per-window cap alone attenuates the contrast to {mg / mt:.2f} of it")

if a.macros:
    rate = float(np.mean([r for r in RATES]))
    pathlib.Path(a.macros).write_text(
        "% Generated by scripts/measure_window_cap.py -- do not edit.\n"
        f"\\newcommand{{\\ppWindowMs}}{{{W * dt * 1000:.0f}}}\n"
        f"\\newcommand{{\\ppWindowBins}}{{{W}}}\n"
        f"\\newcommand{{\\ppWindowFs}}{{{spec.fs:.0f}}}\n"
        f"\\newcommand{{\\ppWindowCapCost}}{{{(1 - mg / mt) * 100:.0f}\\%}}\n"
        f"\\newcommand{{\\ppEventsPerMin}}{{{rate:.0f}}}\n"
        f"\\newcommand{{\\ppWindowCapSeeds}}{{{a.seeds}}}\n")
    print(f"wrote {a.macros}")
