#!/usr/bin/env python3
"""Akaike criterion of AR(p) noise on the recordings' pre-injection windows, for the Methods.

    python scripts/paper_ar_order.py --macros <paper>/generated/ar_order_numbers.tex

Why p = 2: the spectral distance of Supplementary Fig. 1 does not separate
AR(1) from AR(2) -- each misses a different end of the spectrum -- so the order is chosen by
likelihood. Yule-Walker fits per session, conditional Gaussian likelihood of the residuals.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from scipy.linalg import solve_toeplitz

from photosvi.data.bonaventura3 import FS, PRE_S, load_sessions

ap = argparse.ArgumentParser()
ap.add_argument("--macros", required=True)
ap.add_argument("--max-order", type=int, default=4)
a = ap.parse_args()


def aic(v: np.ndarray, p: int) -> float:
    v = v - v.mean()
    n = v.size
    if p == 0:
        res = v
    else:
        r = np.array([np.dot(v[:n - k], v[k:]) / n for k in range(p + 1)])
        phi = solve_toeplitz((r[:p], r[:p]), r[1:p + 1])
        X = np.column_stack([v[p - k - 1:n - k - 1] for k in range(p)])
        res = v[p:] - X @ phi
    m = res.size
    return float(m * (np.log(2 * np.pi * res.var()) + 1) + 2 * (p + 1))


rows = [[aic(np.asarray(s.y[:int(PRE_S * FS)], float), p) for p in range(a.max_order + 1)]
        for s in load_sessions(verbose=False, als_lambda_per_fs=1e4)]
A = np.array(rows)
d12 = A[:, 1] - A[:, 2]
best = A.argmin(1)
fmt = lambda x: f"{x:,.0f}".replace(",", "{,}")  # noqa: E731
macros = {"ArAicNSessions": str(len(A)), "ArAicOneTwoLo": fmt(d12.min()),
          "ArAicOneTwoHi": fmt(d12.max()), "ArAicTwoWins": str(int((d12 > 0).sum())),
          "ArAicBestMax": str(int(best.max()))}
Path(a.macros).write_text("% Generated by scripts/paper_ar_order.py -- do not edit.\n"
                          + "".join(f"\\newcommand{{\\pp{k}}}{{{v}}}\n" for k, v in macros.items()))
print(f"wrote {a.macros}: {macros}")
