#!/usr/bin/env python3
"""Supplementary figure: recordings the fitted model generates back.

    python scripts/paper_fig_predictive.py --data <trace>.json --out .../fig_predictive.pdf

Drawn from the FITTED globals -- each trace samples the coefficients from their posterior
and runs the generative process forward -- so it asks whether a recording the fitted model
would produce looks like the one it was given. A fit can score well on detection and still
imply a recording nothing like the data, and this is the only check that would show it.

It was panel C of the fit figure until 2026-10-05. At a third of a page the traces were too
compressed to read, and it is a check a reader may want to run rather than a result they
need in the main text -- so it gets its own page and the height to be legible.
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib

import matplotlib
import numpy as np

matplotlib.use("Agg")
matplotlib.rcParams["pdf.fonttype"] = 42
matplotlib.rcParams["ps.fonttype"] = 42
import matplotlib.pyplot as plt  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--data",
                default=os.path.join(os.environ.get("PHOTOSVI_RUNS", "runs"), "traces/fit_2.00.json"))
ap.add_argument("--out", default="diagnostics/fig_predictive.pdf")
ap.add_argument("--window-s", type=float, default=120.0,
                help="seconds to draw; the whole recording is unreadable")
ap.add_argument("--t0-s", type=float, default=1000.0)
ap.add_argument("--macros", default=None,
                help="write the counts the caption states to this .tex")
a = ap.parse_args()

D = json.load(open(a.data))
dt = D["dt"]
y = np.array(D["y"])
pp = [np.array(p) for p in D["pp"]]
if not pp:
    raise SystemExit(f"{a.data} carries no posterior-predictive draws")
# A window, not the whole recording. Forty minutes is 115000 samples drawn into some
# fifteen hundred pixels, where every trace becomes a solid band and whether one looks like
# another cannot be judged -- which is the only thing this figure is for. The counts beside
# each panel are over the WHOLE recording; the drawing is a window of it.
i0 = int(a.t0_s / dt)
i1 = min(len(y), i0 + int(a.window_s / dt))
tm = np.arange(i0, i1) * dt
y = y[i0:i1]
pp = [p[i0:i1] for p in pp]
C_FIT = "#eb6834"

# One row per trace rather than stacked with an offset: with the height available they can
# each have their own axis, which is what makes the amplitudes comparable by eye.
n = 1 + len(pp)
fig, axes = plt.subplots(n, 1, figsize=(11.0, 1.5 * n + 0.8), sharex=True, sharey=True)
fig.patch.set_facecolor("white")
axes[0].plot(tm, y, lw=.6, color="#4a4a4a")
axes[0].set_ylabel("observed", fontsize=9.5, color="#4a4a4a")
for i, (ax, p) in enumerate(zip(axes[1:], pp), start=1):
    ax.plot(tm, p, lw=.6, color=C_FIT)
    ax.set_ylabel(f"draw {i}", fontsize=9.5, color=C_FIT)
    ax.text(0.995, 0.92, f"{D['pp_n'][i-1]} events in the recording", transform=ax.transAxes,
            ha="right", va="top", fontsize=8.5, color=C_FIT)
# A simulated recording knows its events; an experimental one has only the fit's expectation
# of them, sum_t q(s_t = 1), which is what the draws' counts are compared with there.
n_obs = len(D["onsets"]) if "onsets" in D else int(D["n_obs"])
obs_label = D.get("obs_label", "events")
axes[0].text(0.995, 0.92, f"{n_obs} {obs_label} in the recording", transform=axes[0].transAxes,
             ha="right", va="top", fontsize=8.5, color="#4a4a4a")
axes[-1].set_xlabel("time (s)")
axes[0].set_xlim(tm[0], tm[-1])
for ax in axes:
    ax.grid(alpha=.13, lw=.7)
    ax.set_axisbelow(True)
    ax.tick_params(labelsize=9, colors="#555555")
    for sp in ax.spines.values():
        sp.set_color("#cccccc")
out = pathlib.Path(a.out)
out.parent.mkdir(parents=True, exist_ok=True)
fig.tight_layout()
fig.savefig(out, transparent=True, bbox_inches="tight")  # PDF: no white patch over LaTeX labels
fig.savefig(out.with_suffix(".png"), dpi=150, facecolor="white", bbox_inches="tight")
if a.macros:
    pathlib.Path(a.macros).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(a.macros).write_text(
        "% Generated by scripts/paper_fig_predictive.py -- do not edit by hand.\n"
        f"\\newcommand{{\\ppFitTrueEvents}}{{{n_obs}}}\n"
        f"\\newcommand{{\\ppFitDraws}}{{{len(pp)}}}\n"
        f"\\newcommand{{\\ppFitDrawRange}}{{{min(D['pp_n'])}--{max(D['pp_n'])}}}\n")
    print(f"  wrote {a.macros}")
print(f"  wrote {out}: {n_obs} {obs_label}, draws {D['pp_n']}")
