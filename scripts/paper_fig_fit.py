"""Paper figure: the fitted model on a representative simulated recording.

Three panels at two time scales, because one will not do: the pharmacokinetic
carrier takes tens of minutes to rise and fall, and the transients it carries are
tenths of a second wide. Panel A is the whole recording, panel B a one-minute
window, panel C traces the fitted model generates back.
"""
import argparse
import json
import os
import pathlib

import matplotlib
import numpy as np
import yaml

matplotlib.use("Agg")
# TrueType, not Type 3, so the PDF's text stays selectable and editable in a vector
# editor -- and so journals that reject Type 3 fonts accept it.
matplotlib.rcParams["pdf.fonttype"] = 42
matplotlib.rcParams["ps.fonttype"] = 42
from pathlib import Path

import matplotlib.pyplot as plt

from photosvi.benchmark import match_events, nms, peaks_from_score

ap = argparse.ArgumentParser()
# A cell of the benchmark grid, generated by scripts/paper_fig_fit_data.py and kept with the
# runs. The previous default was a sigma_y of 0.50 -- a transient-to-noise ratio of twelve,
# far easier than anything the benchmark or the recordings carry -- in a scratch directory
# that does not outlive the session that wrote it.
ap.add_argument("--data",
                default=os.path.join(os.environ.get("PHOTOSVI_RUNS", "runs"), "traces/fit_2.00.json"))
ap.add_argument("--config", default=str(
    pathlib.Path(__file__).resolve().parent.parent / "configs/benchmark_guppy_48.yaml"))
ap.add_argument("--out", default="diagnostics/fig_fit.pdf",
                help="vector output; a .png of the same stem is written alongside")
ap.add_argument("--zoom-t0", type=float, default=1000.0)
ap.add_argument("--zoom-dur", type=float, default=60.0)
a = ap.parse_args()

D = json.load(open(a.data))
dt, INJ, T = D["dt"], D["inj"], D["T"]
y = np.array(D["y"]); xt = np.array(D["x_true"]); xf = np.array(D["x_fit"]); q = np.array(D["q"])
ons = np.array(D["onsets"])
# The detection settings come from the config, like everything else here: a refractory
# period written as a bin count beside a config that states it in seconds is how a detector
# ends up with two different durations at two sampling rates.
_cfg = yaml.safe_load(open(a.config))
_det, _fs = _cfg["detection"], _cfg["data"]["fs"]
TOL = int(round(float(_det["tol_s"]) * _fs))
pk, ps = nms(*peaks_from_score(q), refractory=int(_det["refractory"]))
# Drawn at the threshold that maximises F1, which is the operating point the benchmark
# table reports. A fixed cut at q > 0.5 is the wrong question for a calibrated posterior
# over a sparse process -- it called 190 of 466 events here, all of them correct, which
# makes the panel look like a precision demonstration rather than the fit it is showing.
_order = np.argsort(-np.asarray(ps))
_tp = match_events(np.asarray(pk), np.asarray(ps), ons, TOL, 0)[_order]
_ctp, _cfp = np.cumsum(_tp), np.cumsum(~_tp)
_prec, _rec = _ctp / (_ctp + _cfp), _ctp / max(len(ons), 1)
_f1 = 2 * _prec * _rec / (_prec + _rec + 1e-12)
CUT = float(np.asarray(ps)[_order][int(np.argmax(_f1))])
calls = np.array([int(v) for v, s in zip(pk, ps) if s >= CUT])
tp = sum(1 for c in calls if len(ons) and min(abs(c - ons)) <= TOL)

C_TRUE, C_FIT, C_OBS = "#2a78d6", "#eb6834", "#c3c5ca"
fig = plt.figure(figsize=(11.5, 6.2))
gs = fig.add_gridspec(2, 1, height_ratios=[2.5, 2.3], hspace=.38)
fig.patch.set_facecolor("white")

# --- A: the whole recording, where the tonic carrier is visible ---------------
ax = fig.add_subplot(gs[0])
tm = np.arange(T) * dt / 60
ax.plot(tm, y, lw=.35, color=C_OBS, zorder=1)
ax.plot(tm, xt, lw=2.2, color=C_TRUE, ls="--", label="tonic, true", zorder=3)
ax.plot(tm, xf, lw=2.0, color=C_FIT, label="tonic, fitted", zorder=4)
ax.axvline(INJ * dt / 60, color="#8a8a8a", lw=1.2, ls="--")
ax.text(INJ * dt / 60, ax.get_ylim()[1], " injection", va="top", fontsize=9, color="#555")
ax.set_ylabel("z-scored dF/F"); ax.set_xlabel("time (min)"); ax.set_xlim(0, tm[-1])
ax.legend(loc="upper right", fontsize=9, ncol=2, framealpha=.95)
ax.set_title("A   The whole recording: the pharmacokinetic carrier, true and fitted",
             loc="left", fontweight="bold", fontsize=11)

# --- B: one minute, where the transients are ----------------------------------
ax = fig.add_subplot(gs[1])
i0, i1 = int(a.zoom_t0 / dt), int((a.zoom_t0 + a.zoom_dur) / dt)
t = np.arange(i0, i1) * dt
ax.plot(t, y[i0:i1], lw=.8, color=C_OBS, zorder=1)
ax.plot(t, xf[i0:i1], lw=1.8, color=C_FIT, zorder=3)
hi, lo = y[i0:i1].max(), y[i0:i1].min(); pad = .11 * (hi - lo)
# Called marks immediately under the true ones. With the trace between them the reader had
# to carry a tick across the recording to see whether it was matched, which is the only
# comparison this panel is for.
for e in [o * dt for o in ons if i0 <= o < i1]:
    ax.plot([e, e], [hi + pad * 2.5, hi + pad * 3.4], color=C_TRUE, lw=1.4)
for e in [c * dt for c in calls if i0 <= c < i1]:
    ax.plot([e, e], [hi + pad * 1.2, hi + pad * 2.1], color=C_FIT, lw=1.4)
# No twinned q axis here: overlaying a 0-1 posterior on a dF/F trace put the
# fitted tonic and the posterior in the same visual band and neither read clearly.
# The event posterior is shown in the detection figure instead.
ax.text(t[0], hi + pad * 3.6, "events, true", color=C_TRUE, fontsize=9)
ax.text(t[0], hi + pad * 0.5, "events, called", color=C_FIT, fontsize=9)
ax.set_ylim(lo - pad * 0.5, hi + pad * 4.4)
ax.set_ylabel("z-scored dF/F"); ax.set_xlabel("time (s)"); ax.set_xlim(t[0], t[-1])
ax.set_title("B   One minute of the same recording, at the transient time scale",
             loc="left", fontweight="bold", fontsize=11)

# Panel C -- the posterior-predictive traces -- moved to its own supplementary figure on
# 2026-10-05. It is a check a reader can run rather than a result they need to read
# here, and at a third of a page the traces were too compressed to show anything.
# scripts/paper_fig_predictive.py draws it with the height it needs.
for x in fig.axes:
    x.grid(alpha=.13, lw=.7); x.set_axisbelow(True)
    for sp in x.spines.values(): sp.set_color("#cccccc")
    x.tick_params(labelsize=9, colors="#555555")
# PDF is the deliverable -- editable vector art, and LaTeX prefers it. The PNG is
# written alongside for quick viewing.
_out = Path(a.out)
fig.savefig(_out, transparent=True, bbox_inches="tight")  # PDF: no white patch over LaTeX labels
fig.savefig(_out.with_suffix(".png"), dpi=200, facecolor="white", bbox_inches="tight")
print(f"wrote {_out} and {_out.with_suffix('.png')}")
print(f"{a.out}\n  sigma_y {D['sigma_y']}  |  {len(calls)} called, {tp} true positives, "
      f"{len(ons)} true events  |  posterior-predictive counts {D['pp_n']}")
