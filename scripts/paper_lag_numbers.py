#!/usr/bin/env python3
"""Macros for the detection comparison's lag correction.

    python scripts/paper_lag_numbers.py --out .../generated/lag_numbers.tex

GuPPy reports the PEAK of a transient and this model reports its onset, so the two are
offset by roughly the kernel's rise time and a comparison that matched them to the same
truth without correcting for it would be scoring GuPPy on a definition it never claimed.
The harness estimates each detector's own systematic offset and subtracts it before
matching; these are the numbers that says so, measured rather than asserted, because the
correction is worth more to the comparator than most of the result.
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys

import numpy as np
import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))
from photosvi.benchmark import (  # noqa: E402
    calibrate_lag,
    guppy_detect,
    match_events,
    nms,
    peaks_from_score,
    zpeaks_detect,
)
from photosvi.models.points import build_kernel  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--data",
                default=os.path.join(os.environ.get("PHOTOSVI_RUNS", "runs"), "traces/fit_2.00.json"))
ap.add_argument("--config", default=str(REPO / "configs/benchmark_guppy_48.yaml"))
ap.add_argument("--runs",
                default=os.path.join(os.environ.get("PHOTOSVI_RUNS", "runs"), "runs_benchmark_48"),
                help="the benchmark cells, to report the lag ACROSS them rather "
                     "than on one recording")
ap.add_argument("--out", required=True)
a = ap.parse_args()

D = json.load(open(a.data))
cfg = yaml.safe_load(open(a.config))
det, k, fs = cfg["detection"], cfg["kernel"], cfg["data"]["fs"]
dt = 1.0 / fs
TOL = int(round(det["tol_s"] * fs))
kern = build_kernel(dict(k["fit"]), k["length"], dt).numpy()
peak_bin = int(np.argmax(kern))
CAP_PAD_S = 0.5                      # the matching window extends this far past the kernel peak
cap = peak_bin + int(round(CAP_PAD_S * fs))
ons = np.asarray(D["onsets"])
y = np.asarray(D["y"])


def best_f1(pt, ps, lag):
    o = np.argsort(-np.asarray(ps))
    tp = match_events(np.asarray(pt), np.asarray(ps), ons, TOL, lag)[o]
    ctp, cfp = np.cumsum(tp), np.cumsum(~tp)
    prec, rec = ctp / (ctp + cfp), ctp / max(len(ons), 1)
    return float((2 * prec * rec / (prec + rec + 1e-12)).max())


pk, ps = nms(*peaks_from_score(np.asarray(D["q"])), refractory=det["refractory"])
gt, gs = guppy_detect(y, fs=fs)
gpk, gps = nms(np.asarray(gt), np.asarray(gs), refractory=det["refractory"])
inj = int(D.get("inj_t", cfg["data"]["inj_t"]))
zt, zs = zpeaks_detect(y, inj, fs=fs)
zpk, zps = nms(np.asarray(zt), np.asarray(zs), refractory=det["refractory"])

L = {}
for nm, (t, s) in (("Photosvi", (pk, ps)), ("Guppy", (gpk, gps)), ("Zpeaks", (zpk, zps))):
    lag = calibrate_lag(np.asarray(t), ons, max_lag=cap)
    L[nm] = (lag, best_f1(t, s, lag), best_f1(t, s, 0))
    print(f"  {nm}: lag {lag} bins = {lag*dt*1000:.0f} ms, "
          f"F1 {L[nm][1]:.3f} corrected, {L[nm][2]:.3f} uncorrected")

out = [
    "% Generated by scripts/paper_lag_numbers.py -- do not edit by hand.",
    "%",
    "% The detectors answer different questions -- one reports onsets, the other peaks --",
    "% so each one's systematic offset is estimated and subtracted before matching.",
    "",
    f"\\newcommand{{\\ppLagKernelPeak}}{{{peak_bin * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagCap}}{{{cap * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagCapPadS}}{{{CAP_PAD_S:g}}}",
    f"\\newcommand{{\\ppLagTol}}{{{TOL * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagPhotosvi}}{{{L['Photosvi'][0] * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagGuppy}}{{{L['Guppy'][0] * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagGuppyFone}}{{{L['Guppy'][1]:.3f}}}",
    f"\\newcommand{{\\ppLagGuppyFoneRaw}}{{{L['Guppy'][2]:.3f}}}",
    f"\\newcommand{{\\ppLagPhotosviFone}}{{{L['Photosvi'][1]:.3f}}}",
    f"\\newcommand{{\\ppLagPhotosviFoneRaw}}{{{L['Photosvi'][2]:.3f}}}",
    f"\\newcommand{{\\ppLagZpeaks}}{{{L['Zpeaks'][0] * dt * 1000:.0f}}}",
    f"\\newcommand{{\\ppLagZpeaksFone}}{{{L['Zpeaks'][1]:.3f}}}",
    f"\\newcommand{{\\ppLagZpeaksFoneRaw}}{{{L['Zpeaks'][2]:.3f}}}",
]
# The lag every stored cell recorded, which is what the tables rest on -- one trace shows
# the mechanism, thirty show that it is stable across seeds and noise levels.
import glob

cells = {}
for f in glob.glob(f"{a.runs}/bm_*.json"):
    c = json.load(open(f))
    for nm, m in c["detectors"].items():
        if m.get("lag") is not None:
            cells.setdefault(nm, []).append(int(m["lag"]))
if cells:
    g = sorted(cells.get("guppy", []))
    out += [
        "",
        f"\\newcommand{{\\ppLagCells}}{{{len(g)}}}",
        f"\\newcommand{{\\ppLagGuppyMed}}{{{int(np.median(g)) * dt * 1000:.0f}}}",
        f"\\newcommand{{\\ppLagGuppyLo}}{{{min(g) * dt * 1000:.0f}}}",
        f"\\newcommand{{\\ppLagGuppyHi}}{{{max(g) * dt * 1000:.0f}}}",
    ]
    print(f"  across {len(g)} cells: guppy lag {min(g)}-{max(g)} bins")
    z = sorted(cells.get("z-peaks", []))
    out += ([f"\\newcommand{{\\ppLagZpeaksMed}}{{{int(np.median(z)) * dt * 1000:.0f}}}",
             f"\\newcommand{{\\ppLagZpeaksLo}}{{{min(z) * dt * 1000:.0f}}}",
             f"\\newcommand{{\\ppLagZpeaksHi}}{{{max(z) * dt * 1000:.0f}}}"] if z else
            [f"\\newcommand{{\\ppLagZpeaks{x}}}{{\\pppending}}" for x in ("Med", "Lo", "Hi")])

pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
pathlib.Path(a.out).write_text("\n".join(out) + "\n")
print(f"  wrote {a.out}")
