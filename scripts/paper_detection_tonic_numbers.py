"""Macros for the tonic side of the detection benchmark (generated/detection_tonic_numbers.tex).

Per noise level (ordinal in increasing noise, as paper_benchmark_numbers.py) and per method
-- PhotoSVI's fitted tonic, the lab's 0.1 Hz low-pass, and its ALS baseline -- the error of
the two summaries scripts/detection_tonic.py takes from every curve: the height of the
post-injection peak above the pre-injection level (estimate minus truth, in the trace's
units, and as a percentage of the true height), and the time of that peak after the
injection (estimate minus truth, in minutes). Mean +- sd over seeds.

    python scripts/paper_detection_tonic_numbers.py --runs DIR --out generated/detection_tonic_numbers.tex
"""
import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from detection_tonic import area_rel_err  # noqa: E402

ORD = ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten")
METHODS = (("photosvi", "Photosvi"), ("lowpass", "Lowpass"), ("als", "Als"))

ap = argparse.ArgumentParser()
ap.add_argument("--runs", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()

cells = defaultdict(list)
for f in sorted(glob.glob(f"{a.runs}/bm_*.json")):
    c = json.load(open(f))
    if "tonic" in c:
        cells[float(c["sigma_y"])].append(c)
if not cells:
    raise SystemExit(f"no cells with a tonic record in {a.runs}")


def errors(C, m):
    h = np.array([c["tonic"]["summary"][m]["peak_height"]
                  - c["tonic"]["summary"]["true"]["peak_height"] for c in C])
    rel = 100 * h / np.array([c["tonic"]["summary"]["true"]["peak_height"] for c in C])
    t = np.array([c["tonic"]["summary"][m]["peak_time_s"]
                  - c["tonic"]["summary"]["true"]["peak_time_s"] for c in C]) / 60
    ar = np.array([area_rel_err(c["tonic"], m) for c in C])
    return h, rel, t, ar


levels = sorted(cells)
n_seeds = min(len(v) for v in cells.values())
lines = ["% Generated by scripts/paper_detection_tonic_numbers.py -- do not edit by hand.",
         f"% From {os.path.abspath(a.runs)}: {len(levels)} noise levels, {n_seeds} seeds each.",
         ""]
for i, s in enumerate(levels):
    nm = ORD[i]
    for m, tag in METHODS:
        h, rel, t, ar = errors(cells[s], m)
        p = f"\\ppTonicDet"
        lines += [
            f"\\newcommand{{{p}HeightErr{tag}{nm}}}{{{h.mean():+.2f} \\pm {h.std(ddof=1):.2f}}}",
            f"\\newcommand{{{p}HeightErr{tag}{nm}Mean}}{{{h.mean():+.2f}}}",
            f"\\newcommand{{{p}HeightRelErr{tag}{nm}}}{{{rel.mean():+.0f}}}",
            f"\\newcommand{{{p}HeightAbsRelErr{tag}{nm}}}{{{np.abs(rel).mean():.0f}}}",
            f"\\newcommand{{{p}TimeErr{tag}{nm}}}{{{t.mean():+.1f} \\pm {t.std(ddof=1):.1f}}}",
            f"\\newcommand{{{p}TimeErr{tag}{nm}Mean}}{{{t.mean():+.1f}}}",
            f"\\newcommand{{{p}TimeAbsErr{tag}{nm}}}{{{np.abs(t).mean():.1f}}}",
            f"\\newcommand{{{p}HeightRelErrSd{tag}{nm}}}{{{rel.std(ddof=1):.0f}}}",
            f"\\newcommand{{{p}AreaRelErr{tag}{nm}}}{{{ar.mean():+.1f}}}",
            f"\\newcommand{{{p}AreaRelErrSd{tag}{nm}}}{{{ar.std(ddof=1):.1f}}}",
        ]
    lines.append("")
tr = cells[levels[0]][0]["tonic"]["summary"]["true"]
lines += [f"\\newcommand{{\\ppTonicDetSeeds}}{{{n_seeds}}}",
          f"\\newcommand{{\\ppTonicDetTrueHeight}}{{{tr['peak_height']:.2f}}}",
          f"\\newcommand{{\\ppTonicDetTrueTimeMin}}{{{tr['peak_time_s'] / 60:.1f}}}",
          "\\newcommand{\\ppTonicDetLowpassHz}{0.1}"]
open(a.out, "w").write("\n".join(lines) + "\n")
print(f"  {a.out}: {len(levels)} levels x {n_seeds} seeds")
for i, s in enumerate(levels):
    for m, tag in METHODS:
        h, rel, t, ar = errors(cells[s], m)
        print(f"    sigma {s:g} {m:9s} height {h.mean():+.3f} +- {h.std(ddof=1):.3f} "
              f"({rel.mean():+.1f}%)  time {t.mean():+.2f} +- {t.std(ddof=1):.2f} min  "
              f"area {ar.mean():+.1f} +- {ar.std(ddof=1):.1f}%")
