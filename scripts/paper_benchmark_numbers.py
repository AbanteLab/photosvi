#!/usr/bin/env python3
"""Regenerate the benchmark macros from the run directory.

    python scripts/paper_benchmark_numbers.py --runs runs_benchmark_48 \
        --out ../../papers/photosvi-paper/generated/benchmark_numbers.tex

These were hand-written until 2026-10-01, which is why they survived a change of kernel, of
emission, of effect size and of noise grid without anyone noticing they described a different
experiment. A generator makes the paper's numbers a function of the runs, so a rerun that
changes them cannot leave the text behind.

One macro set per noise level, named by ordinal in increasing noise, plus the grid's own
shape. Levels are ordered by sigma_y so the table reads from easiest to hardest whatever the
config happens to list.
"""
from __future__ import annotations

import argparse
import glob
import json
import math
import os
import pathlib
from collections import defaultdict

import numpy as np
import yaml

ORD = ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten")

ap = argparse.ArgumentParser()
ap.add_argument("--runs", default="runs_benchmark_48")
ap.add_argument("--out", required=True)
ap.add_argument("--mu-a", type=float, default=None,
                help="mark median in log space, for the transient-to-noise ratio; "
                     "read from the config when omitted")
# Resolved against the repo, not the caller's directory: the paper's Makefile runs this
# from the paper repo, where a relative path finds nothing.
ap.add_argument("--config", default=str(
    pathlib.Path(__file__).resolve().parent.parent / "configs/benchmark_guppy_48.yaml"))
a = ap.parse_args()

cells = defaultdict(list)
# bm_*.json: the 30-seed directory (runs_final_detection_t30) also keeps its launch logs and
# may gain other JSONs; the cells are only ever the bm_ files.
for f in sorted(glob.glob(f"{a.runs}/bm_*.json")):
    c = json.load(open(f))
    cells[float(c["sigma_y"])].append(c)
if not cells:
    raise SystemExit(f"no cells in {a.runs}")
if len({len(v) for v in cells.values()}) > 1:
    print(f"  warning: unequal seeds per level in {a.runs}: "
          + ", ".join(f"{s:g}: {len(v)}" for s, v in sorted(cells.items())))

if a.mu_a is None:
    a.mu_a = float(yaml.safe_load(open(a.config))["gt"]["mu_a"])
amp = math.exp(a.mu_a)

levels = sorted(cells)
lines = [
    "% Generated by scripts/paper_benchmark_numbers.py -- do not edit by hand.",
    f"% From {os.path.abspath(a.runs)}: {len(levels)} noise levels, "
    f"{min(len(v) for v in cells.values())} seeds each.",
    "",
]


def fmt(v, sd, places=3):
    return f"{v:.{places}f} \\pm {sd:.{places}f}"


# z-peaks (the Bonaventura lab's prominence rule) joins the table when every cell carries
# it; benchmarks run before 2026-10-20 do not, and its macros are then placeholders.
DETS = [("guppy", "Guppy"), ("photosvi", "Photosvi")]
if all("z-peaks" in c["detectors"] for v in cells.values() for c in v):
    DETS.append(("z-peaks", "Zpeaks"))

truth = None
for i, s in enumerate(levels):
    C = cells[s]
    nm = ORD[i]
    tnr = amp / s
    lines.append(f"\\newcommand{{\\ppBmTnr{nm}}}{{{tnr:.1f}}}")
    lines.append(f"\\newcommand{{\\ppBmSigma{nm}}}{{{s:g}}}")
    # Per metric, the better of the two is emitted in bold. Done here rather than in the
    # .tex so that a rerun which flips a cell moves the bold with it: a table whose
    # emphasis has to be maintained by hand is a table that will eventually emphasise the
    # loser. Only the point estimate is bolded, not the spread.
    for key, mac in (("best_f1", "FOne"), ("pr_auc", "PrAuc"), ("recall_at", "RecallAt")):
        vals = {det: np.array([c["detectors"][det][key] for c in C], dtype=float)
                for det, _ in DETS}
        best = max(vals, key=lambda d: vals[d].mean())
        means = sorted((v.mean() for v in vals.values()), reverse=True)
        if abs(means[0] - means[1]) < 5e-4:
            best = None          # a tie for first place emphasises neither
        if len(DETS) == 2:
            for m in ("", "Mean"):
                lines.append(f"\\newcommand{{\\ppBm{mac}Zpeaks{nm}{m}}}{{\\pppending}}")
        for det, tag in DETS:
            v = vals[det]
            mean = f"\\mathbf{{{v.mean():.3f}}}" if det == best else f"{v.mean():.3f}"
            lines.append(
                f"\\newcommand{{\\ppBm{mac}{tag}{nm}}}{{{mean} \\pm {v.std():.3f}}}")
            lines.append(f"\\newcommand{{\\ppBm{mac}{tag}{nm}Mean}}{{{v.mean():.3f}}}")
    rate = np.array([math.exp(c["beta_inj"]) for c in C], dtype=float)
    mle = np.array([c["beta_inj"] - c["mle"] for c in C], dtype=float)
    lines.append(f"\\newcommand{{\\ppBmRate{nm}}}{{{fmt(rate.mean(), rate.std())}}}")
    lines.append(f"\\newcommand{{\\ppBmBias{nm}}}{{{mle.mean():+.3f}}}")
    st = [c.get("stopped_at") for c in C if c.get("stopped_at")]
    lines.append(f"\\newcommand{{\\ppBmStopped{nm}}}{{{int(np.median(st)) if st else 0}}}")
    npred = np.array([c["detectors"]["photosvi"]["n_pred"] for c in C], dtype=float)
    ncand = np.array([c["detectors"]["guppy"]["n_pred"] for c in C], dtype=float)
    lines.append(f"\\newcommand{{\\ppBmCandPhotosvi{nm}}}{{{npred.mean():.0f}}}")
    lines.append(f"\\newcommand{{\\ppBmCandGuppy{nm}}}{{{ncand.mean():.0f}}}")
    lines.append("")
    truth = C[0]

lines += [
    f"\\newcommand{{\\ppBmSeeds}}{{{min(len(v) for v in cells.values())}}}",
    f"\\newcommand{{\\ppBmLevels}}{{{len(levels)}}}",
    f"\\newcommand{{\\ppBmCells}}{{{sum(len(v) for v in cells.values())}}}",
    # The benchmark's own sampling rate. It is NOT \ppFs: that is the rate the cohort
    # simulations run at, and the benchmark moved to the recordings' own 48 Hz so it could
    # be anchored to them without a conversion. Two rates in one paper needs two macros.
    f"\\newcommand{{\\ppBmFs}}{{{int(yaml.safe_load(open(a.config))['data']['fs'])}}}",
    f"\\newcommand{{\\ppBmMinutes}}{{"
    f"{yaml.safe_load(open(a.config))['data']['T'] / yaml.safe_load(open(a.config))['data']['fs'] / 60:.0f}}}",
    f"\\newcommand{{\\ppBmTnrHigh}}{{{amp / levels[0]:.1f}}}",
    f"\\newcommand{{\\ppBmTnrLow}}{{{amp / levels[-1]:.1f}}}",
    f"\\newcommand{{\\ppBmNTrue}}{{{int(np.mean([c['n_true'] for v in cells.values() for c in v]))}}}",
]
g = yaml.safe_load(open(a.config))["gt"]
lines.append(f"\\newcommand{{\\ppBmTrueRatio}}{{{math.exp(g['beta_inj']):.0f}}}")
lines.append(f"\\newcommand{{\\ppBmTrueRateMin}}{{"
             f"{60 * math.exp(g['beta0']):.1f}}}")
open(a.out, "w").write("\n".join(x for x in lines if x is not None) + "\n")
print(f"  {a.out}: {len(levels)} levels x "
      f"{min(len(v) for v in cells.values())} seeds, TNR "
      f"{amp/levels[0]:.1f} down to {amp/levels[-1]:.1f}")
