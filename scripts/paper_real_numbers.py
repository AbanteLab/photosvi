#!/usr/bin/env python3
"""Macros for the real-cohort section, from the cohort fit the paper reports.

    python scripts/paper_real_numbers.py --fit runs_real_final/full_noDL56sali.json \
        --out ../../papers/photosvi-paper/generated/real_numbers.tex

The paper's analysis is one crossed fit of the nociceptin cohort, both
batches (7 animals), without DL56's morphine-only session (13 sessions). The incomplete-
design refit and the alternative-initialization refit of earlier versions are no longer
reported, so their macros are left to generated/pending.tex.

Rate: the log-rate contrast RO64-6198 minus vehicle and its 90% interval, with the posterior
width averaged over the last TAIL convergence probes as the contrast is (the width oscillates
between probes). Tonic: the contrast of the tonic peak height (log P, RO64 minus vehicle,
from the fitted tonic hierarchy) as a ratio with its 90% interval, and the fitted time to
peak per condition -- reported because both peaks fall beyond the recorded window, so the
height is an extrapolation of the fitted curve.
"""
from __future__ import annotations

import argparse
import json
import math

Z90 = 1.6448536269514722
TAIL = 6

ap = argparse.ArgumentParser()
ap.add_argument("--fit", default="runs_real_final/full_noDL56sali.json")
ap.add_argument("--out", required=True)
ap.add_argument("--placeholder", action="store_true",
                help="emit every macro as \\pppending so the paper compiles before the fit")
a = ap.parse_args()

NAMES = ("Animals", "Sessions", "Contrast", "Ci", "Ratio", "RatioCi", "TonicRatio",
         "TonicRatioCi", "TonicPeakNoci", "TonicPeakVeh", "WindowPre", "WindowPost",
         "SigmaLo", "SigmaHi", "SigmaY", "MaskPct", "MaskMin", "MaskLo", "MaskHi", "ArOrder",
         "Phi", "KernelTaps", "FullAnimals", "FullSessions", "FullContrast", "FullCi",
         "FullRatio", "FullRatioCi", "Excluded")
if a.placeholder:
    open(a.out, "w").write("% Placeholder from scripts/paper_real_numbers.py --placeholder.\n"
                           + "".join(f"\\newcommand{{\\ppReal{n}}}{{\\pppending}}\n"
                                     for n in NAMES))
    raise SystemExit(0)

d = json.load(open(a.fit))
tr = [t["sd"] for t in d.get("trajectory", []) if isinstance(t, dict) and "sd" in t]
sd = sum(tr[-TAIL:]) / len(tr[-TAIL:]) if tr else d["contrast_sd"]
c = d["contrast"]
lo, hi = c - Z90 * sd, c + Z90 * sd
tc, tsd = d["tonic_contrast_alpha"]
tlo, thi = tc - Z90 * tsd, tc + Z90 * tsd
tp = d["tonic_posterior"]
FS, PRE = d["fs"], d["pre_s"] / 60.0
sig = d["sigma_y_sessions"]
S = d["sessions"]
rec = [x["mask_s"][1] - x["mask_s"][0] for x in S]
masked = sum(FS * x.get("mask_used_s", x["mask_s"][1] - x["mask_s"][0]) for x in S)
excl = ", ".join(f"{e}" for e in d.get("exclude", [])) or "none"
v = {
    "Animals": str(d["n_animals"]), "Sessions": str(d["n_sessions"]),
    "Contrast": f"{c:+.2f}", "Ci": f"[{lo:+.2f},\\,{hi:+.2f}]",
    "Ratio": f"{math.exp(c):.2f}", "RatioCi": f"[{math.exp(lo):.2f},\\,{math.exp(hi):.2f}]",
    "TonicRatio": f"{math.exp(tc):.2f}",
    "TonicRatioCi": f"[{math.exp(tlo):.2f},\\,{math.exp(thi):.2f}]",
    "TonicPeakNoci": f"{tp['nociceptin']['peak_s'] / 60:.0f}",
    "TonicPeakVeh": f"{tp['saline']['peak_s'] / 60:.0f}",
    "WindowPre": f"{PRE:.0f}", "WindowPost": f"{d['T'] / FS / 60 - PRE:.1f}",
    "SigmaLo": f"{min(sig):.4f}", "SigmaHi": f"{max(sig):.4f}",
    "SigmaY": f"{d['sigma_y']:.4f}",
    "MaskPct": f"{100 * masked / (d['T'] * d['n_sessions']):.1f}",
    "MaskMin": f"{d.get('mask_min_s', 0):g}",
    "MaskLo": f"{min(rec):.0f}", "MaskHi": f"{max(rec):.0f}",
    "ArOrder": str(len(d["ar_coeffs"])),
    "Phi": "[" + ", ".join(f"{x:.3f}" for x in d["ar_coeffs"]) + "]",
    "KernelTaps": str(d["kernel_length"]),
    "Excluded": excl,
}
# The Full* names the text used before the rewrite, now with this fit's values.
v.update({"FullAnimals": v["Animals"], "FullSessions": v["Sessions"],
          "FullContrast": v["Contrast"], "FullCi": v["Ci"], "FullRatio": v["Ratio"],
          "FullRatioCi": v["RatioCi"]})
L = ["% Generated by scripts/paper_real_numbers.py -- do not edit by hand.",
     f"% Fit: {a.fit}; 90% intervals; width averaged over the last {TAIL} probes.",
     f"% Tonic peaks fall at {v['TonicPeakNoci']} (RO64) and {v['TonicPeakVeh']} (vehicle) "
     f"min after morphine, beyond the {v['WindowPost']}-min window: the height is extrapolated."]
L += [f"\\newcommand{{\\ppReal{n}}}{{{v[n]}}}" for n in NAMES]
open(a.out, "w").write("\n".join(L) + "\n")
print(f"  {a.out}: contrast {c:+.3f} sd {sd:.3f} ratio {math.exp(c):.2f} "
      f"{v['RatioCi']} | tonic ratio {v['TonicRatio']} {v['TonicRatioCi']} | peaks "
      f"{v['TonicPeakNoci']}/{v['TonicPeakVeh']} min")
