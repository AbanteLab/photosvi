#!/usr/bin/env python3
"""Assemble the power grid into the paper's macros and a tidy table.

    python scripts/paper_power_numbers.py --runs <dir> \
        --out ../../papers/photosvi-paper/generated/power_numbers.tex \
        --json <dir>/summary.json

The grid is one directory per (design, number of animals), each holding every effect size,
because `cohort_report.py` calibrates each arm's threshold on that cell's own null cohorts.
This runs that report per cell and collects what the paper states: power at a matched
false-positive rate, the width of the hierarchical interval, and its coverage.

Cells that have not finished are skipped and named, so a partial grid produces a partial
table rather than nothing -- the grid is worked in priority order precisely so that a
partial table is still the one the paper needs.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser()
ap.add_argument("--runs", required=True, help="the grid's output directory")
ap.add_argument("--out", required=True)
ap.add_argument("--json", default=None, help="also write the assembled summary here")
ap.add_argument("--alpha", type=float, default=0.05)
ap.add_argument("--min-cohorts", type=int, default=6,
                help="a cell with fewer finished cohorts than this is reported as partial")
a = ap.parse_args()

CELL = re.compile(r"(crossed|uncrossed)_n(\d+)$")
cells = []
for d in sorted(glob.glob(os.path.join(a.runs, "*_n*"))):
    m = CELL.search(os.path.basename(d))
    if not m:
        continue
    design, n = m.group(1), int(m.group(2))
    n_sessions = 2 * n                      # two conditions, and the uncrossed design of
    if design == "uncrossed":               # this study gives each animal one of them
        n_sessions = n
    cells.append((design, n, n_sessions, d))

if not cells:
    raise SystemExit(f"no cells under {a.runs}")

summary = []
for design, n, n_sessions, d in cells:
    tmp = os.path.join(d, "_report.json")
    r = subprocess.run(
        [sys.executable, str(REPO / "scripts/cohort_report.py"), "--runs", d,
         "--alpha", str(a.alpha), "--n-sessions", str(n_sessions), "--json", tmp],
        capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0 or not os.path.exists(tmp):
        print(f"  {design} n={n}: report failed, skipped\n    {r.stderr.strip()[:200]}")
        continue
    rep = json.load(open(tmp))
    rows = rep["rows"]
    done = len(rows)
    summary.append(dict(design=design, n_animals=n, n_sessions=n_sessions,
                        n_cohorts=done, partial=done < a.min_cohorts,
                        alpha=rep["alpha"], thresholds=rep["thresholds"], rows=rows))
    print(f"  {design:<10} n={n:<3} sessions={n_sessions:<3} cohorts={done}"
          + ("  (partial)" if done < a.min_cohorts else ""))

L = ["% Generated by scripts/paper_power_numbers.py -- do not edit by hand.",
     "%",
     "% One cell per (design, number of animals). A cell marked partial has fewer finished",
     "% cohorts than the grid asked for; the grid is worked in priority order, so a partial",
     "% table is the one the paper needs rather than a uniform fraction of everything.",
     ""]
L.append(f"\\newcommand{{\\ppPowAlpha}}{{{a.alpha:.0%}}}".replace("%", r"\%"))
L.append(f"\\newcommand{{\\ppPowCells}}{{{len(summary)}}}")
if summary:
    ns = sorted({s["n_animals"] for s in summary if s["design"] == "crossed"})
    L.append(f"\\newcommand{{\\ppPowNList}}{{{', '.join(str(x) for x in ns)}}}")
    L.append(f"\\newcommand{{\\ppPowSeeds}}{{{max(s['n_cohorts'] for s in summary)}}}")
pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
pathlib.Path(a.out).write_text("\n".join(L) + "\n")
print(f"  wrote {a.out}: {len(summary)} cells")
if a.json:
    json.dump(summary, open(a.json, "w"), indent=1)
    print(f"  wrote {a.json}")
